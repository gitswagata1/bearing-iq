"""Remaining-useful-life (RUL) estimation from a degrading vibration signal.

PROTOTYPE · SYNTHETIC DATA. The sensor histories below are generated by
`_simulate_history` (exponential degradation + Gaussian noise, fixed seeds).
They are not plant measurements.

Model (deliberately simple and inspectable):
  1. Health indicator: RMS vibration v(t) in mm/s, sampled hourly.
  2. Degradation model: v(t) = v0 + exp(a + b*t). We estimate v0 as the median
     of the first 48 h, then fit log(v - v0) = a + b*t by least squares on the
     most recent window of readings.
  3. Failure is defined as v crossing a fixed alarm threshold (THRESHOLD_MM_S).
     Point RUL = time until the fitted curve reaches the threshold.
  4. Uncertainty: residual bootstrap (refit on resampled residuals) gives a
     distribution of RUL -> P10 / P50 / P90 and P(failure within horizon).
  5. Health score = 100 * (1 - (v_now - v0) / (threshold - v0)), clipped 0..100.

Validation: `backtest()` replays each synthetic run-to-failure history, makes a
prediction at several cut-off points and compares predicted vs. true RUL
(MAE, and how often the true RUL falls inside the P10-P90 band).
"""

from __future__ import annotations

import numpy as np
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel

router = APIRouter(prefix="/api/rul", tags=["Remaining Useful Life (prototype)"])

THRESHOLD_MM_S = 7.1  # alarm level chosen for this demo
FIT_WINDOW_H = 120  # hours of recent data used for the fit
N_BOOT = 300
HORIZON_H = 72  # horizon for "probability of failure"

# id, name, seed, total life (h), current age (h)
ASSETS = [
    ("GRD-01", "Grinding Machine #1 · spindle bearing", 11, 1400, 700),
    ("GRD-03", "Grinding Machine #3 · spindle bearing", 23, 1100, 1055),
    ("HT-01", "Heat Treatment Furnace #1 · fan bearing", 37, 1600, 1530),
    ("TURN-01", "CNC Turning Center #1 · spindle bearing", 41, 1300, 900),
]


def _simulate_history(seed: int, life_h: int) -> np.ndarray:
    """Full synthetic run-to-failure vibration trace (hourly, mm/s)."""
    rng = np.random.default_rng(seed)
    v0 = rng.uniform(1.6, 2.3)
    # choose b so the curve hits the threshold exactly at life_h
    a = np.log(rng.uniform(0.02, 0.06))
    b = (np.log(THRESHOLD_MM_S - v0) - a) / life_h
    t = np.arange(life_h + 1)
    clean = v0 + np.exp(a + b * t)
    noise = rng.normal(0, 0.06 + 0.03 * (clean - v0), size=t.size)
    return np.clip(clean + noise, 0.5, None)


def _fit(t: np.ndarray, v: np.ndarray, v0: float):
    y = np.log(np.clip(v - v0, 1e-3, None))
    b, a = np.polyfit(t, y, 1)
    resid = y - (a + b * t)
    return a, b, resid


def _rul_from(a: float, b: float, t_now: float, v0: float) -> float:
    if b <= 0:
        return float("inf")
    t_fail = (np.log(THRESHOLD_MM_S - v0) - a) / b
    return max(0.0, t_fail - t_now)


def predict(v: np.ndarray, seed: int = 0) -> dict:
    t = np.arange(v.size, dtype=float)
    v0 = float(np.median(v[:48]))
    w = slice(max(0, v.size - FIT_WINDOW_H), v.size)
    tw, vw = t[w], v[w]
    a, b, resid = _fit(tw, vw, v0)
    t_now = float(t[-1])
    rul = _rul_from(a, b, t_now, v0)

    rng = np.random.default_rng(seed)
    yhat = a + b * tw
    boots = []
    for _ in range(N_BOOT):
        yb = yhat + rng.choice(resid, size=resid.size, replace=True)
        bb, ab = np.polyfit(tw, yb, 1)
        boots.append(_rul_from(ab, bb, t_now, v0))
    boots = np.array(boots)
    finite = boots[np.isfinite(boots)]
    cap = 5000.0
    p10, p50, p90 = (np.percentile(np.clip(finite, 0, cap), [10, 50, 90]) if finite.size else (cap, cap, cap))

    v_now = float(np.median(v[-6:]))
    health = 100 * (1 - (v_now - v0) / (THRESHOLD_MM_S - v0))
    return {
        "baseline_mm_s": round(v0, 3),
        "current_mm_s": round(v_now, 3),
        "health_score": int(np.clip(round(health), 0, 100)),
        "rul_hours_point": None if not np.isfinite(rul) else round(rul, 1),
        "rul_hours_p10": round(float(p10), 1),
        "rul_hours_p50": round(float(p50), 1),
        "rul_hours_p90": round(float(p90), 1),
        "failure_prob_within_horizon": round(float(np.mean(boots < HORIZON_H)), 3),
        "fit": {"a": float(a), "b": float(b), "window_start_h": int(tw[0])},
    }


class Point(BaseModel):
    t: int
    v: float


class RulAsset(BaseModel):
    asset_id: str
    name: str
    age_hours: int
    threshold_mm_s: float
    horizon_hours: int
    history: list[Point]
    fitted: list[Point]
    baseline_mm_s: float
    current_mm_s: float
    health_score: int
    failure_prob_within_horizon: float
    rul_hours_point: float | None
    rul_hours_p10: float
    rul_hours_p50: float
    rul_hours_p90: float


class Backtest(BaseModel):
    predictions: int
    mae_hours: float
    mean_true_rul_hours: float
    p10_p90_coverage: float
    note: str


class ModelCard(BaseModel):
    data: str
    features: list[str]
    model: str
    target: str
    uncertainty: str
    validation: Backtest
    limitations: list[str]


def _asset(aid: str) -> RulAsset:
    match = [x for x in ASSETS if x[0] == aid]
    if not match:
        raise HTTPException(404, "unknown asset")
    _, name, seed, life, age = match[0]
    full = _simulate_history(seed, life)
    v = full[: age + 1]
    p = predict(v, seed)
    step = 4
    hist = [Point(t=int(i), v=round(float(v[i]), 3)) for i in range(0, v.size, step)]
    a, b = p["fit"]["a"], p["fit"]["b"]
    v0 = p["baseline_mm_s"]
    t_end = int(age + min(p["rul_hours_p90"], 600))
    fitted = [
        Point(t=int(t), v=round(min(float(v0 + np.exp(a + b * t)), THRESHOLD_MM_S * 1.15), 3))
        for t in range(p["fit"]["window_start_h"], t_end + 1, step)
    ]
    return RulAsset(
        asset_id=aid, name=name, age_hours=age, threshold_mm_s=THRESHOLD_MM_S,
        horizon_hours=HORIZON_H, history=hist, fitted=fitted,
        **{k: p[k] for k in ("baseline_mm_s", "current_mm_s", "health_score",
                             "failure_prob_within_horizon", "rul_hours_point",
                             "rul_hours_p10", "rul_hours_p50", "rul_hours_p90")},
    )


def backtest() -> Backtest:
    errs, covered, trues = [], 0, []
    seeds = range(100, 120)  # 20 held-out synthetic run-to-failure histories
    for s in seeds:
        life = int(np.random.default_rng(s).integers(900, 1800))
        full = _simulate_history(s, life)
        true_fail = int(np.argmax(full >= THRESHOLD_MM_S)) if (full >= THRESHOLD_MM_S).any() else life
        for frac in (0.6, 0.75, 0.9):
            cut = int(true_fail * frac)
            p = predict(full[: cut + 1], s)
            true_rul = true_fail - cut
            est = p["rul_hours_p50"]
            errs.append(abs(est - true_rul))
            trues.append(true_rul)
            covered += p["rul_hours_p10"] <= true_rul <= p["rul_hours_p90"]
    return Backtest(
        predictions=len(errs),
        mae_hours=round(float(np.mean(errs)), 1),
        mean_true_rul_hours=round(float(np.mean(trues)), 1),
        p10_p90_coverage=round(covered / len(errs), 2),
        note="Backtest on 20 synthetic run-to-failure histories not used for the on-screen assets, "
             "predicting at 60%, 75% and 90% of life. Synthetic data follows the same model family, "
             "so these numbers are optimistic versus real sensors.",
    )


_BACKTEST: Backtest | None = None


@router.get("/assets", response_model=list[RulAsset])
async def rul_assets():
    return [_asset(a[0]) for a in ASSETS]


@router.get("/assets/{asset_id}", response_model=RulAsset)
async def rul_asset(asset_id: str):
    return _asset(asset_id)


@router.get("/model-card", response_model=ModelCard)
async def model_card():
    global _BACKTEST
    if _BACKTEST is None:
        _BACKTEST = backtest()
    return ModelCard(
        data="Synthetic hourly RMS vibration (mm/s), exponential degradation + noise. Not plant data.",
        features=["RMS vibration trend (last 120 h)", "Baseline vibration (median of first 48 h)", "Time since install (h)"],
        model="Exponential degradation curve v(t) = v0 + exp(a + b·t), fitted by least squares on log(v − v0); "
              f"failure = crossing {THRESHOLD_MM_S} mm/s.",
        target="Remaining useful life (hours) until the alarm threshold is crossed",
        uncertainty=f"Residual bootstrap ({N_BOOT} refits) → P10/P50/P90 RUL and P(failure within {HORIZON_H} h)",
        validation=_BACKTEST,
        limitations=[
            "Single sensor channel; no temperature/load covariates yet",
            "Assumes monotonic exponential degradation; maintenance resets are not modelled",
            "Validated only on synthetic data; needs real run-to-failure data (e.g. bearing test-rig datasets) before any claim of accuracy",
        ],
    )
